CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE IF NOT EXISTS users(
	user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
	user_name VARCHAR(100) NOT NULL,
	user_email VARCHAR(100) NOT NULL UNIQUE,
	user_password VARCHAR(100) NOT NULL,
	user_age INT CHECK(user_age BETWEEN 0 AND 150),
	user_status INT NOT NULL CHECK(user_status IN(1,2,3)) DEFAULT 1,
	user_level INT NOT NULL CHECK(user_level IN(1,2,3)) DEFAULT 3,
	create_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	update_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	delete_at TIMESTAMPTZ DEFAULT NULL
);

COMMENT ON COLUMN users.user_status IS 'user_status: 1-ACTIVE, 2-INACTIVE, 3-BANNED';
COMMENT ON COLUMN users.user_level IS 'user_level: 1-ADMIN, 2-VIP, 3-MEMBER';
COMMENT ON COLUMN users.user_age IS 'user_age must be less than 150 and greater than 0';

CREATE INDEX idx_user_status ON users (user_status);
CREATE INDEX idx_user_level ON users (user_level);
CREATE INDEX idx_user_name ON users (user_name);
CREATE INDEX idx_user_status_create_at ON users (user_status,create_at);

CREATE OR REPLACE FUNCTION fc_update_at()
RETURNS TRIGGER AS $$
BEGIN
	NEW.update_at:=NOW();
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_before_update_at
BEFORE UPDATE 
ON users
FOR EACH ROW
EXECUTE FUNCTION fc_update_at();